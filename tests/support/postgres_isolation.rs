//! A unique database isolates both global outboxes and database-scoped locks.
pub struct IsolatedPostgres {
    administrative: sqlx::PgPool,
    name: String,
    url: url::Url,
}

impl IsolatedPostgres {
    pub async fn create(database_url: &str) -> Self {
        let administrative = sqlx::PgPool::connect(database_url).await.unwrap();
        let name = format!("mtc_atomic_test_{}", uuid::Uuid::now_v7().simple());
        sqlx::query(sqlx::AssertSqlSafe(format!("CREATE DATABASE {name}")))
            .execute(&administrative)
            .await
            .unwrap();
        let mut url = url::Url::parse(database_url).unwrap();
        url.set_path(&name);
        Self {
            administrative,
            name,
            url,
        }
    }

    pub fn url(&self) -> &str {
        self.url.as_str()
    }

    pub async fn cleanup(self) {
        // Only the database generated by this fixture is eligible for removal.
        sqlx::query(sqlx::AssertSqlSafe(format!(
            "DROP DATABASE {} WITH (FORCE)",
            self.name
        )))
        .execute(&self.administrative)
        .await
        .unwrap();
        self.administrative.close().await;
    }
}
